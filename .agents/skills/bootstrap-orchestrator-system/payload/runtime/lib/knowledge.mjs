// Knowledge catalogue (contracts/knowledge-catalog.md). Knowledge documents are markdown files under the
// knowledge root, each with a front matter that declares its tier. The catalogue assigns file ids by path
// order and is rebuilt on every call, so an id is valid only for the current index. The last index is
// cached under <cache root> (default <sessions root>/.cache/) for humans; the knowledge folder itself is never written by a read.
import { existsSync, readFileSync, readdirSync, statSync } from "node:fs";
import { join, relative } from "node:path";
import { RuntimeError, arg, frontmatter, parseFrontmatter, requireString, writeText } from "./util.mjs";

export const TIERS = {
  MustHave: "Mandatory knowledges for the project. Agent must always apply them",
  PerContext: "Context depending knowledges. Agent must evalueate them as context evolve",
  PerComponent: "Component depending knowledges. Agent must evalueate them based on the component involved in its implementation",
};
const CATALOG_FILE = "knowledge-catalog.yaml";
const SETTINGS_FILE = "kbsettings.yaml";

function globToRegExp(glob) {
  let pattern = "";
  for (let i = 0; i < glob.length; i++) {
    const c = glob[i];
    if (c === "*" && glob[i + 1] === "*") {
      pattern += glob[i + 2] === "/" ? "(?:.*/)?" : ".*";
      i += glob[i + 2] === "/" ? 2 : 1;
    } else if (c === "*") pattern += "[^/]*";
    else pattern += c.replace(/[.+?^${}()|[\]\\]/g, "\\$&");
  }
  return new RegExp(`^${pattern}$`);
}

function excludes(root) {
  const path = join(root, SETTINGS_FILE);
  if (!existsSync(path)) return [];
  const patterns = [];
  let inExcludes = false;
  for (const line of readFileSync(path, "utf8").split("\n")) {
    if (/^excludes:\s*$/.test(line)) inExcludes = true;
    else if (inExcludes && /^\s*-\s+/.test(line)) patterns.push(line.replace(/^\s*-\s+/, "").replace(/^["']|["']$/g, "").trim());
    else if (/^\S/.test(line)) inExcludes = false;
  }
  return patterns.map(globToRegExp);
}

function documents(ctx) {
  const root = ctx.knowledgeRoot;
  if (!existsSync(root)) return [];
  const skip = excludes(root);
  const files = [];
  const walk = (dir) => {
    for (const entry of readdirSync(dir).sort()) {
      const path = join(dir, entry);
      if (statSync(path).isDirectory()) walk(path);
      else if (entry.endsWith(".md") && entry !== "README.md") files.push(relative(root, path).split("\\").join("/"));
    }
  };
  walk(root);
  return files.filter((file) => !skip.some((re) => re.test(file))).sort();
}

export function buildCatalog(ctx) {
  return documents(ctx).map((path, index) => {
    const { data } = parseFrontmatter(readFileSync(join(ctx.knowledgeRoot, path), "utf8"));
    const tier = TIERS[data.tier] ? data.tier : "PerContext";
    const keywords = Array.isArray(data.keywords) ? data.keywords.join(", ") : (data.keywords ?? "");
    return { file_id: index + 1, path, tier, title: data.title ?? path, keywords, intent: data.intent ?? "", IsEditable: data.editable !== false };
  });
}

function catalogYaml(entries) {
  const lines = [];
  for (const [tier, description] of Object.entries(TIERS)) {
    lines.push(`${tier}:`, `  section_description: ${description}`, "  knowledges:");
    const inTier = entries.filter((e) => e.tier === tier);
    if (inTier.length === 0) lines.push("  []");
    for (const e of inTier) {
      lines.push(`  - file_id: ${e.file_id}`, `    keywords: ${e.keywords ? e.keywords : "''"}`, `    intent: ${e.intent}`, `    IsEditable: ${e.IsEditable}`);
    }
  }
  return `${lines.join("\n")}\n`;
}

function writeIndex(ctx, entries) {
  const index = entries.map((e) => `# file_id ${e.file_id}: ${e.path} (${e.tier})`).join("\n");
  writeText(join(ctx.cacheRoot, CATALOG_FILE), `# Generated by the agentic system runtime. File ids follow path order and change on rebuild.\n${index}\n${catalogYaml(entries)}`);
}

export function catalog(ctx) {
  if (!existsSync(ctx.knowledgeRoot)) {
    return `The knowledge base is empty: ${ctx.knowledgeRoot} does not exist.\n${catalogYaml([])}`;
  }
  const entries = buildCatalog(ctx);
  writeIndex(ctx, entries);
  return catalogYaml(entries);
}

export function rebuild(ctx) {
  const entries = buildCatalog(ctx);
  writeIndex(ctx, entries);
  return `Knowledge index rebuilt: ${entries.length} knowledge document(s).`;
}

function idsOf(args) {
  const raw = arg(args, "fileIds") ?? arg(args, "fileId") ?? arg(args, "ids") ?? arg(args, "id");
  const list = Array.isArray(raw) ? raw : String(raw ?? "").split(",");
  const ids = list.map((v) => Number(String(v).trim())).filter((n) => Number.isInteger(n) && n > 0);
  if (ids.length === 0) throw new RuntimeError("knowledge-read failed: pass one or more file ids (fileIds).");
  return ids;
}

export function read(ctx, args) {
  const entries = buildCatalog(ctx);
  const parts = [];
  for (const id of idsOf(args)) {
    const entry = entries.find((e) => e.file_id === id);
    if (!entry) {
      parts.push(`# file_id ${id}\n(not found in the current index: call knowledge-catalog again, file ids change on rebuild)`);
      continue;
    }
    parts.push(`# file_id ${id} — ${entry.title}\n${readFileSync(join(ctx.knowledgeRoot, entry.path), "utf8").trim()}`);
  }
  return `${parts.join("\n\n---\n\n")}\n`;
}

function slug(title) {
  return title.replace(/[^A-Za-z0-9_]/g, "_").replace(/_+/g, "_").slice(0, 60);
}

export function create(ctx, args) {
  const tool = "knowledge-create";
  const title = requireString(arg(args, "title"), "title", tool);
  const content = requireString(arg(args, "content"), "content", tool);
  const tier = arg(args, "tier") ?? "PerContext";
  if (!TIERS[tier]) throw new RuntimeError(`${tool} failed: tier must be one of ${Object.keys(TIERS).join(", ")}`);
  const folder = arg(args, "folder") ?? "";
  const path = join(ctx.knowledgeRoot, folder, `${slug(title)}.md`);
  if (existsSync(path)) throw new RuntimeError(`${tool} failed: a knowledge document already exists at ${relative(ctx.knowledgeRoot, path)}; use knowledge-update.`);
  const keywords = arg(args, "keywords");
  writeText(path, frontmatter({ title, tier, keywords, intent: arg(args, "intent") ?? "", editable: true }) + content.trimEnd() + "\n");
  const entry = buildCatalog(ctx).find((e) => join(ctx.knowledgeRoot, e.path) === path);
  writeIndex(ctx, buildCatalog(ctx));
  return `Knowledge created: file_id ${entry?.file_id ?? "?"} (${relative(ctx.knowledgeRoot, path)}).`;
}

export function update(ctx, args) {
  const tool = "knowledge-update";
  const id = idsOf({ fileIds: arg(args, "fileId") ?? arg(args, "id") })[0];
  const content = requireString(arg(args, "content"), "content", tool);
  const entry = buildCatalog(ctx).find((e) => e.file_id === id);
  if (!entry) throw new RuntimeError(`${tool} failed: file_id ${id} is not in the current index; call knowledge-catalog again.`);
  if (!entry.IsEditable) throw new RuntimeError(`${tool} failed: file_id ${id} is not editable.`);
  const path = join(ctx.knowledgeRoot, entry.path);
  const { data } = parseFrontmatter(readFileSync(path, "utf8"));
  const intent = arg(args, "intent") ?? data.intent;
  writeText(path, frontmatter({ ...data, intent }) + content.trimEnd() + "\n");
  writeIndex(ctx, buildCatalog(ctx));
  return `Knowledge updated: file_id ${id} (${entry.path}).`;
}
